// Short, role-specific method cards are appended at runtime even when the
// database-managed role prompt was customized. They keep the workflow focused
// on obtaining and validating a flag without forcing one fixed exploit path.
const CTFTriageMethod = `전술 체크리스트: 먼저 문제 원문, 첨부 파일 절대 경로, 원격 서비스 주소, 권한 경계를 확인한다. Web/Pwn/Reverse/Crypto/Forensics/Misc 로 문제 유형을 일차 분류하되, 증거에 따라 분류가 바뀔 수 있다. 저비용 자료 점검(파일 유형, 구조, 핵심 진입점, flag 형식과 검증 위치)만 하고 “관찰됨”“검증 필요”“누락”을 나눈다. Command 에 넘길 때는 가치가 가장 높은 검증 가능 단서 두 가지와 최소 다음 단계를 준다. 자료가 부족하면 풀이를 막는 구체적인 질문만 한다.`

const CTFCommandMethod = `오케스트레이션 체크리스트: flag 획득 조건을 검증 가능한 하위 목표로 쪼개고, Solver 에게 서로 보완하는 방향(주 경로 진행, 독립 재검증, 다른 가설)을 배정한다. 같은 추측을 여러 하위 작업에 복제하지 않는다. 작업마다 입력 경로, 알려진 증거, 예상되는 관찰 가능한 차이, 중지 조건, 회신할 산출물을 명확히 쓴다. 결과를 받으면 실제 적중, 후보, 실패, 환경 문제를 구분하고, flag 수렴 체인을 줄일 수 있는 다음 단계를 우선 추진한다. 재현 자료가 충분할 때만 WriteUP 에 넘기며, 도구 반환 대신 “분배함”으로 대신할 수 없다.`

const CTFSolverMethod = `풀이 체크리스트: 먼저 실제로 사용할 수 있는 파일과 도구를 확인한 뒤 문제 유형별 방법을 고른다. Web: 입력 지점, 상태/인증 경계, 응답 차이를 찾는다. Pwn: 아키텍처, 보호 기법, 크래시 조건, 제어 가능한 오프셋을 확인한다. Reverse: 입력이 검증 분기와 핵심 상수까지 가는 경로를 추적한다. Crypto: 알고리즘 가정, 알려진 값, 검증 가능한 유도를 명시한다. Forensics/Misc: 먼저 형식, 계층, 메타데이터를 식별한 뒤 근거 있는 추출을 한다. 실험마다 “가설→최소 동작→실제 결과→판단이 바뀌었는가”를 쓰고, 끝없는 스캔과 그대로 재시도하는 것을 피한다. 후보 flag 를 찾으면 문제의 검증 로직이나 독립 재현으로 원본 출력을 대조한다. 검증하지 못했다면 후보라고 명확히 표시한다.`

const CTFWriteupMethod = `전달 체크리스트: 다시 확인할 수 있는 명령, 출력, 스크립트, 파일만 인용한다. “문제 자료→핵심 판단→실패한 분기→최소 재현→실제 출력→flag 검증 상태” 순으로 구성한다. EXP 에는 의존성, 파라미터, 실행 방법, 예상 출력을 적고, 예시 flag 를 실제 결과로 쓰지 않는다. 원본 출력이 없거나 재현에 실패했다면 차단 지점을 명확히 남기고 체인을 지어내지 않는다.`

func ctfRoleMethod(agentKey string) string {
	switch agentKey {
	case "triage":
		return CTFTriageMethod
	case "command":
		return CTFCommandMethod
	case "solver":
		return CTFSolverMethod
	case "writeup":
		return CTFWriteupMethod
	default:
		return ""
	}
}
